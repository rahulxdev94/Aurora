import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadConfig} from '../scripts/config.mjs';
import {normaliseNativeGpuUsage,normaliseWeatherPayload} from '../src/live-data/live-data.mjs';
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixture=path.join(project,'.build','config-fixture');
await fs.mkdir(fixture,{recursive:true});
await fs.copyFile(path.join(project,'config.example.json'),path.join(fixture,'config.example.json'));
await fs.writeFile(path.join(fixture,'config.local.json'),'{}');
const defaults=await loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'});
assert.equal(defaults.roots.Desktop,'C:\\Users\\Example\\Desktop');
assert.equal(defaults.chatgptUrl,'https://chatgpt.com/');
assert.equal(defaults.weather.enabled,false);assert.equal(defaults.calendar.enabled,false);
assert.equal(defaults.audio.enabled,false,'System playback integration requires explicit opt-in');
await fs.writeFile(path.join(fixture,'config.local.json'),JSON.stringify({roots:{Desktop:'%USERPROFILE%\\Cloud\\Desktop'},weather:{enabled:true}}));
const custom=await loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'});
assert.equal(custom.roots.Desktop,'C:\\Users\\Example\\Cloud\\Desktop');assert.equal(custom.weather.enabled,true);
assert.equal(custom.audio.enabled,false,'Other configuration changes do not enable audio');
await fs.writeFile(path.join(fixture,'config.local.json'),JSON.stringify({audio:{enabled:true}}));
assert.equal((await loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'})).audio.enabled,true);
await fs.writeFile(path.join(fixture,'config.local.json'),JSON.stringify({audio:{enabled:'true'}}));
await assert.rejects(loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'}),/must be boolean/);
await fs.writeFile(path.join(fixture,'config.local.json'),JSON.stringify({chatgptUrl:'javascript:alert(1)'}));
await assert.rejects(loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'}),/HTTPS or Codex/);
await fs.writeFile(path.join(fixture,'config.local.json'),JSON.stringify({roots:{Desktop:'relative'}}));
await assert.rejects(loadConfig(fixture,{USERPROFILE:'C:\\Users\\Example'}),/absolute Windows/);
assert.equal(normaliseNativeGpuUsage([{name:'Integrated GPU',usage:23}]).usagePct,23,'Portable usage does not require one laptop GPU model');
assert.equal(normaliseNativeGpuUsage([{name:'Unknown',usage:NaN}]).usagePct,null);
assert.throws(()=>normaliseWeatherPayload({timezone:'UTC',daily:{time:[]}}),/Invalid/);
await fs.writeFile(path.join(fixture,'config.local.json'),'{}');
console.log('Portable configuration: disabled integrations, profile defaults, redirected folders, launch URL validation and generic GPU selection passed with synthetic data.');
