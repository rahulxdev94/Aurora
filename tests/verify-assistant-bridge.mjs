const win={CustomEvent:class{constructor(type,{detail}){this.type=type;this.detail=detail;}},setTimeout(fn){timers.set(++serial,fn);return serial;},clearTimeout(id){timers.delete(id);}};
const doc={defaultView:win,hidden:false,addEventListener(){},removeEventListener(){}};
const root={ownerDocument:doc,dispatchEvent:event=>events.push(event)};
const dispose=initAssistantBridge({root,invoke:()=>{calls++;return new Promise((resolve,reject)=>{resolveRead=resolve;rejectRead=reject;});},SeelenCommand:{ReadFile:'read'},now:()=>now});
const tick=[...timers.values()][0];tick();assert.equal(calls,1,'Slow native reads must not pile up');
resolveRead(JSON.stringify(base));await Promise.resolve();await Promise.resolve();
