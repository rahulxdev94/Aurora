import assert from 'node:assert/strict';
import {normaliseAssistantPresence,initAssistantBridge} from '../src/aurora-assistant-bridge.mjs';
const now=100000,base={schema_version:1,id:'one',source:'Codex',state:'working',message:'Checking the desktop layout.',observedAt:now-1000,expiresAt:now+45000};
assert.equal(normaliseAssistantPresence(base,now).state,'working');
assert.equal(normaliseAssistantPresence({...base,expiresAt:now},now),null);
assert.equal(normaliseAssistantPresence({...base,observedAt:now+2000},now),null);
for(const state of ['listening','speaking','thinking'])assert.throws(()=>normaliseAssistantPresence({...base,state},now));
assert.throws(()=>normaliseAssistantPresence({...base,source:'voice-session'},now));
assert.throws(()=>normaliseAssistantPresence({...base,expiresAt:now+90000},now));
assert.equal(normaliseAssistantPresence({...base,message:'<script>do not run</script>'},now).message,'<script>do not run</script>');
