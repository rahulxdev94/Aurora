tick();rejectRead(new Error('Temporary read failure'));await Promise.resolve();await Promise.resolve();
tick();resolveRead(JSON.stringify(base));await Promise.resolve();await Promise.resolve();
assert.equal(events.filter(event=>event.type==='aurora:assistant-status').length,2,'Recovery must restore a still-fresh entry after a transient failure');
dispose();dispose();
