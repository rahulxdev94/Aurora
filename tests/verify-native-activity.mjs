import assert from 'node:assert/strict';
import {initNativeActivity} from '../src/aurora-native-activity.mjs';
const received=[];
const root={ownerDocument:{defaultView:{CustomEvent:class{constructor(type,options){this.type=type;this.detail=options.detail;}}}},dispatchEvent:event=>received.push(event)};
let listener,stopped=0;
const cleanup=initNativeActivity({root,subscribe:async(name,callback)=>{assert.equal(name,'aurora:activity');listener=callback;return()=>stopped++;}});
const drain=async()=>{for(let i=0;i<8;i++)await Promise.resolve();};
await drain();
for(const payload of [null,{},'anything',{message:'hello',kind:'execute'},{message:4,kind:'info'}])listener({payload});
assert.equal(received.length,0);
listener({payload:{message:'Opened an app',kind:'success',command:'ignored'}});
assert.deepEqual(received[0].detail,{message:'Opened an app',kind:'success'});
listener({payload:{message:'x'.repeat(1000),kind:'error'}});
assert.equal(received[1].detail.message.length,160);
cleanup();assert.equal(stopped,1);listener({payload:{message:'late',kind:'info'}});assert.equal(received.length,2);
let resolveSubscription,lateStopped=0;
const early=initNativeActivity({root,subscribe:()=>new Promise(resolve=>resolveSubscription=resolve)});
await drain();early();resolveSubscription(()=>lateStopped++);await drain();assert.equal(lateStopped,1);
console.log('Native activity: bounded status-only payloads, invalid event rejection and late subscription cleanup passed.');
